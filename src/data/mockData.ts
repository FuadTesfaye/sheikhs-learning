export const lessons: Lesson[] = [
  // 1. Kitab At-Tawheed (32 complete lessons with authentic Cloudflare R2 audio & PDF textbook)
  ...Array.from({ length: 32 }, (_, i) => {
    const lessonNum = String(i + 1).padStart(2, '0');
    const audioUrl = getR2Url(`kitabu-tawhid/lesson-${lessonNum}.mp3`);
    const pdfUrl = getR2Url('kitabu-tawhid/lesson-01.pdf');
    const duration = tawheedDurations[i] || 1800;

    return {
      id: `crs-1-les-${i + 1}`,
      courseId: 'crs-1',
      title: tawheedTitles[i] || `الدرس ${i + 1}: من كتاب التوحيد`,
      description: `شرح تفصيلي معتمد للباب ${i + 1} من كِتَابِ التَّوْحِيدِ بصوت الشيخ رحمه الله، مع المتن الدراسي المضبوط بالشكل.`,
      duration,
      order: i + 1,
      type: 'audio' as const,
      mediaUrl: audioUrl,
      audioOnlyUrl: audioUrl,
      pdfUrl,
      transcriptText: `المتن الدراسي والشرح المعتمد للباب ${i + 1} من كِتَابِ التَّوْحِيدِ للإمام المجدد محمد بن عبد الوهاب رحمه الله.`,
      isAvailable: true,
    };
  }),

  // 2. Verified Syllabi for the Sheikh's Authentic Recorded Kitabs (crs-2 through crs-7)
  ...Object.entries(syllabusByCourse).flatMap(([courseId, titles]) => {
    return titles.map((title, idx) => ({
      id: `${courseId}-les-${idx + 1}`,
      courseId,
      title,
      description: `مفردات ومنهج دراسي معتمد لكتاب ${courses.find(c => c.id === courseId)?.title || ''}.`,
      duration: 1200 + idx * 60,
      order: idx + 1,
      type: 'audio' as const,
      mediaUrl: '',
      audioOnlyUrl: '',
      pdfUrl: undefined,
      transcriptText: `ملخص منهجي وعناصر الدرس ${idx + 1} المعتمدة للدراسة والحفظ.`,
      isAvailable: false,
    }));
  }),
];

export const getCoursesByCategory = (categoryId: string): Course[] =>
  courses.filter(c => c.categoryId === categoryId);

export const getLessonsByCourse = (courseId: string): Lesson[] =>
  lessons.filter(l => l.courseId === courseId).sort((a, b) => a.order - b.order);

export const getCourseById = (courseId: string): Course | undefined =>
  courses.find(c => c.id === courseId);

export const getLessonById = (lessonId: string): Lesson | undefined =>
  lessons.find(l => l.id === lessonId);

export const getCategoryById = (categoryId: string): Category | undefined =>
  categories.find(c => c.id === categoryId);
